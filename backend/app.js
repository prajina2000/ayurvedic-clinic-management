import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import { env } from './config/env.js';
import authRoutes from './routes/authRoutes.js';
import receptionRoutes from './routes/receptionRoutes.js';
import doctorRoutes from './routes/doctorRoutes.js';
import pharmacyRoutes from './routes/pharmacyRoutes.js';
import procedureRoutes from './routes/procedureRoutes.js';
import accountRoutes from './routes/accountRoutes.js';
import userRoutes from './routes/userRoutes.js';
import whatsappRoutes from './routes/whatsappRoutes.js';
import { authenticate } from './middleware/auth.js';
import { errorHandler, notFound } from './middleware/errors.js';
import { dashboard } from './controllers/dashboardController.js';
import { getDb } from './config/db.js';

const app=express();
app.use(helmet());
app.use(cors({origin:env.frontendUrl}));
app.use(express.json({limit:'1mb',verify:(req,res,buffer)=>{req.rawBody=Buffer.from(buffer);}}));
app.get('/api/health',async(req,res)=>{try{await getDb().command({ ping: 1 });res.json({status:'ok',database:'postgresql'});}catch{res.status(503).json({status:'unavailable',database:'postgresql'});}});
app.use('/api/auth/login',rateLimit({windowMs:15*60*1000,limit:10,standardHeaders:true,legacyHeaders:false}));
app.use('/api/auth',authRoutes);
app.use('/api/reception',receptionRoutes);
app.use('/api/doctor',doctorRoutes);
app.use('/api/pharmacy',pharmacyRoutes);
app.use('/api/procedures',procedureRoutes);
app.use('/api/accounts',accountRoutes);
app.use('/api/users',userRoutes);
app.use('/api/dashboard',authenticate,dashboard);
app.get('/api/clinic',authenticate,(req,res)=>res.json({name:env.appName,address:env.clinicAddress,phone:env.clinicPhone,currency:env.currency,timezone:env.timezone}));
app.use('/api/webhooks/whatsapp',whatsappRoutes);
app.use(notFound,errorHandler);
export default app;
